test('terminal stays focused through button submissions and failed requests', async ({ page }) => {
  await register(page, 'Focus')
  await page.getByRole('button', { name: 'Terminal launcher', exact: true }).click()
  const input = page.getByRole('textbox', { name: 'Terminal command', exact: true })
  await expect(input).toBeFocused()
  await page.route('**/command/', async route => {
    await new Promise(resolve => setTimeout(resolve, 250))
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Test connection interrupted' }) })
  })
  await input.fill('status')
  await page.getByRole('button', { name: 'Execute command', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Test connection interrupted')
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('status')
  await page.unroute('**/command/')
  await cmd(page, 'status', 'Balance: 1200 CPH')
  await page.getByRole('button', { name: 'Desktop', exact: true }).focus()
  await expect(input).not.toBeFocused()
})

test('bankrupt runner can explicitly restart one slot and preserve the other', async ({ page }) => {
  await register(page, 'Broke')
  const slots = await page.request.get('/api/slots/')
  const slotId = (await slots.json()).slots[0].id
  await post(page, 'slots/', { position: 2, alias: 'Untouched' })
  for (const product_id of ['cpu-1-specialist', 'memory-1-specialist', 'monitor-1-standard', 'decryptor-1-standard']) {
    await post(page, `slots/${slotId}/loadout/`, { action: 'buy', product_id })
  }
  await post(page, `slots/${slotId}/applications/`, { action: 'launch', product_id: 'terminal' })
  for (const id of ['0-0', '0-1', '0-2', '1-0']) {
    await post(page, `slots/${slotId}/command/`, { application: 'terminal', command: `accept ${id}` })
    await post(page, `slots/${slotId}/command/`, { application: 'terminal', command: 'abort' })
  }
  await page.reload()
  await expect(page.locator('.stat-value').first()).toContainText('0')
  await page.getByRole('button', { name: 'Restart this runner' }).click()
  await expect(page.getByRole('button', { name: 'Erase progress and restart' })).toBeDisabled()
  await page.getByLabel('TYPE Broke TO CONFIRM').fill('Broke')
  await page.getByRole('button', { name: 'Erase progress and restart' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.stat-value').first()).toContainText('1,200')
  const finalSlots = (await (await page.request.get('/api/slots/')).json()).slots
  expect(finalSlots.find(slot => slot.position === 2).balance).toBe(1200)
})

