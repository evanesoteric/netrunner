import { test, expect } from '@playwright/test'

const passphrase = 'Quieter!Nebula-97-signal'

test('account, three saves, contract payout, bank ledger, upgrade and persistence', async ({ page }) => {
  const handle = `e2e_${Date.now()}`
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1, name: 'The network' })).toBeVisible()
  await page.getByLabel('RUNNER HANDLE').fill(handle)
  await page.getByLabel('PASSPHRASE', { exact: true }).fill(passphrase)
  await page.getByRole('button', { name: 'Create identity' }).click()
  await expect(page.getByRole('heading', { name: 'Choose your connection' })).toBeVisible()
  await page.getByLabel('RUNNER ALIAS').first().fill('Nightwire')
  await page.getByRole('button', { name: 'Initialize slot' }).first().click()
  await expect(page.getByRole('heading', { name: 'Welcome back, Nightwire' })).toBeVisible()
  await page.getByRole('button', { name: 'Find a contract' }).click()
  await expect(page.locator('.contract-card')).toHaveCount(4)
  await expect(page.getByRole('button', { name: 'Accept job' }).nth(2)).toBeDisabled()
  await page.getByRole('button', { name: 'Accept job' }).first().click()
  await expect(page.getByRole('heading', { name: 'Follow the signal' })).toBeVisible()
  for (const command of ['scan', 'breach', 'extract', 'wipe', 'disconnect']) {
    await page.getByLabel('Nightwire@remote:~$').fill(command)
    await page.getByRole('button', { name: 'Execute command' }).click()
    await expect(page.getByRole('log')).toContainText(`> ${command}`)
  }
  await expect(page.getByRole('log')).toContainText('Contract complete. +220 CPH')
  await page.getByRole('button', { name: 'Cipher bank' }).click()
  await expect(page.locator('.bank-hero h2')).toContainText('1,420')
  await expect(page.locator('.ledger-row')).toHaveCount(2)
  await page.getByRole('button', { name: 'My gateway' }).click()
  await page.getByRole('button', { name: 'Install upgrade' }).first().click()
  await expect(page.getByRole('heading', { name: 'Processor MK.2' })).toBeVisible()
  await page.getByRole('button', { name: 'Cipher bank' }).click()
  await expect(page.locator('.bank-hero h2')).toContainText('1,120')
  await expect(page.locator('.ledger-row')).toHaveCount(3)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Welcome back, Nightwire' })).toBeVisible()
  await page.getByRole('button', { name: 'Nightwire SLOT' }).click()
  await page.getByLabel('RUNNER ALIAS').first().fill('Secondlife')
  await page.getByRole('button', { name: 'Initialize slot' }).first().click()
  await expect(page.getByRole('heading', { name: 'Welcome back, Secondlife' })).toBeVisible()
  await expect(page.locator('.stat-value').first()).toContainText('1,200')
  await page.getByRole('button', { name: 'Secondlife SLOT' }).click()
  await page.getByLabel('RUNNER ALIAS').fill('Thirdsignal')
  await page.getByRole('button', { name: 'Initialize slot' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back, Thirdsignal' })).toBeVisible()
  await page.getByRole('button', { name: 'Thirdsignal SLOT' }).click()
  await expect(page.getByRole('button', { name: 'Initialize slot' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Connect', exact: true }).first().click()
  await expect(page.getByRole('button', { name: 'Manage save slots' })).toBeHidden()
  await page.screenshot({ path: '../.local/dashboard-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByLabel('RUNNER HANDLE').fill(handle)
  await page.getByLabel('PASSPHRASE', { exact: true }).fill(passphrase)
  await page.getByRole('button', { name: 'Connect to gateway' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back, Nightwire' })).toBeVisible()
  await expect(page.locator('.stat-value').first()).toContainText('1,120')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Welcome back, Nightwire' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../.local/dashboard-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Manage save slots' }).click()
  await expect(page.locator('.save-card')).toHaveCount(3)
  await page.getByRole('button', { name: 'Connect', exact: true }).first().click()
  await page.getByRole('button', { name: 'Cipher bank', exact: true }).click()
  await expect(page.locator('.bank-hero h2')).toContainText('1,120')
})

test('login terminal adapts to mobile and displays server validation errors', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Create identity' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByLabel('RUNNER HANDLE').fill('mobile_test')
  await page.getByLabel('PASSPHRASE', { exact: true }).fill('123456789')
  await page.getByRole('button', { name: 'Create identity' }).click()
  await expect(page.getByRole('alert')).toContainText('entirely numeric')
  await page.screenshot({ path: '../.local/access-mobile.png', fullPage: true })
})
