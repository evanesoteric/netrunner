async function apps(page) {
  await page.getByRole('button', { name: 'Application launcher', exact: true }).first().click()
}
async function launch(page, name) {
  await apps(page)
  await page.getByRole('button', { name: new RegExp(`^(Launch|Open) ${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`) }).click()
}
async function process(page, name) {
  await page.locator('.application-dock').getByRole('button', { name, exact: true }).click()
}
async function sidebar(page, name) {
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true }).click()
}
async function cmd(page, command, expected) {
  if (command.startsWith('crack ')) { await breakPassword(page); return }
  const input = page.getByRole('textbox', { name: 'Terminal command', exact: true })
  await expect(input).toBeFocused()
  await input.fill(command)
  const response = page.waitForResponse(r => r.url().endsWith('/command/') && r.request().method() === 'POST')
  await input.press('Enter')
  expect((await response).status()).toBe(200)
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
  if (expected) await expect(page.getByRole('log')).toContainText(expected)
}
async function breakPassword(page, scope = page) {
  const breaker = scope.getByRole('region', { name: 'Lockpick password breaker', exact: true })
  await expect(breaker).toBeVisible()
  await expect(breaker.getByRole('textbox', { name: 'Login username', exact: true })).toHaveValue('admin')
  await breaker.getByRole('button', { name: 'Break password', exact: true }).click()
  await expect(breaker.getByRole('status')).toHaveText('BREAKING PASSWORD')
  await expect(breaker.getByRole('status')).toHaveText('PASSWORD DECODED', { timeout: 30000 })
  await expect(breaker.getByRole('textbox', { name: 'Password', exact: true })).toHaveValue('************')
  const login = page.waitForResponse(r => r.url().endsWith('/password-breaker/') && r.request().method() === 'POST')
  await breaker.getByRole('button', { name: 'Login', exact: true }).click()
  expect((await login).status()).toBe(200)
}
async function post(page, path, payload) {
  const cookies = await page.context().cookies()
  const response = await page.request.post('/api/' + path, { data: payload, headers: { 'X-CSRFToken': cookies.find(c => c.name === 'csrftoken').value } })
  expect(response.ok()).toBeTruthy()
  return response.json()
}

async function contractId(page, target = 'helix-0.internal') {
  const slots = (await (await page.request.get('/api/slots/')).json()).slots
  const slot = await (await page.request.get(`/api/slots/${slots[0].id}/`)).json()
  return slot.contracts.find(job => job.target === target).id
}

